#!/usr/bin/env python3
"""Unit tests for ``scripts/content.py``.

Run with::

    python3 -m unittest discover -s scripts/tests -v

The tests only use fixtures below ``scripts/tests/fixtures``; production
content is never required.
"""

from __future__ import annotations

import contextlib
import importlib.util
import io
import json
import re
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

TESTS_DIR = Path(__file__).resolve().parent
SCRIPTS_DIR = TESTS_DIR.parent
FIXTURES_DIR = TESTS_DIR / "fixtures"
VALID_FIXTURE = FIXTURES_DIR / "valid"
INVALID_FIXTURE = FIXTURES_DIR / "invalid"
SAFE_NAMES_FIXTURE = FIXTURES_DIR / "safe-names"

#: Keys that must never be exported into catalog.json.
FORBIDDEN_CATALOG_KEYS = {
    "value",
    "flag_value",
    "template",
    "secret",
    "token",
    "password",
    "env",
    "solution",
}

CONTENT_META_TEMPLATE = """\
name = "{name}"
version = "1.0.0"
author = "dev@floatctf.local"
category = "web"
difficulty = "easy"
tags = []
description = "generated by tests"
{safe_name}
"""


def _load_content_module():
    spec = importlib.util.spec_from_file_location(
        "floatctf_content", SCRIPTS_DIR / "content.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["floatctf_content"] = module
    spec.loader.exec_module(module)
    return module


content = _load_content_module()


def quiet(function, *args, **kwargs):
    """Call *function* while swallowing stdout/stderr."""

    with contextlib.redirect_stdout(io.StringIO()):
        with contextlib.redirect_stderr(io.StringIO()):
            return function(*args, **kwargs)


def copy_fixture(fixture: Path, destination: Path) -> Path:
    shutil.copytree(fixture, destination, dirs_exist_ok=True)
    return destination


def write_content(
    root: Path,
    kind: str,
    content_id: str,
    *,
    safe_name: str | None = None,
    dockerfile: bool = False,
) -> Path:
    """Create a minimal content directory below *root* (kind: challenges/...)."""

    directory = root / kind / content_id
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "meta.toml").write_text(
        CONTENT_META_TEMPLATE.format(
            name=content_id,
            safe_name=f'safe_name = "{safe_name}"' if safe_name else "",
        ),
        encoding="utf-8",
    )

    if dockerfile:
        source = directory / "src"
        source.mkdir(parents=True, exist_ok=True)
        (source / "Dockerfile").write_text("FROM scratch\n", encoding="utf-8")

    return directory


def find_entry(entries: list[dict], content_id: str) -> dict:
    for entry in entries:
        if entry["id"] == content_id:
            return entry
    raise AssertionError(f"{content_id!r} missing")


def json_keys(node) -> set[str]:
    """Collect every dict key used anywhere in *node*."""

    keys: set[str] = set()

    if isinstance(node, dict):
        for key, value in node.items():
            keys.add(key)
            keys |= json_keys(value)
    elif isinstance(node, list):
        for item in node:
            keys |= json_keys(item)

    return keys


