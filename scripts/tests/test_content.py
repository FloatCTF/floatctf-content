class CatalogTests(unittest.TestCase):
    def catalog(self) -> dict:
        return content.build_catalog(VALID_FIXTURE)

    def entry(self, collection: str, content_id: str) -> dict:
        for item in self.catalog()[collection]:
            if item["id"] == content_id:
                return item
        raise AssertionError(f"{collection}/{content_id} missing from catalog")

    def test_catalog_root_structure(self) -> None:
        catalog = self.catalog()

        self.assertEqual(
            list(catalog.keys()),
            ["version", "challenges", "gameboxes", "events"],
        )
        self.assertEqual(catalog["version"], 1)

    def test_catalog_challenge_generation(self) -> None:
        self.assertEqual(
            self.entry("challenges", "comment"),
            {
                "id": "comment",
                "name": "comment",
                "version": "1.0.0",
                "author": "fb0sh@outlook.com",
                "category": "web",
                "difficulty": "easy",
                "tags": ["php", "web"],
                "description": "注释里面有什么？",
                "image": "floatctf/comment:challenge-v1.0.0",
                "flag": {"type": "dynamic"},
                "docker": {
                    "port": 80,
                    "recommended_resources": {
                        "cpu_millis": 500,
                        "memory_bytes": 268435456,
                        "pids_limit": 100,
                    },
                },
                "events": ["freshcup"],
            },
        )

    def test_catalog_gamebox_generation(self) -> None:
        self.assertEqual(
            self.entry("gameboxes", "comment"),
            {
                "id": "comment",
                "name": "comment",
                "version": "1.0.0",
                "author": "dev@floatctf.local",
                "category": "misc",
                "difficulty": "medium",
                "tags": ["box"],
                "description": "GameBox fixture",
                "image": "floatctf/comment:gamebox-v1.0.0",
                "docker": {"port": 8080},
                "events": ["freshcup"],
            },
        )

    def test_catalog_challenge_without_events_or_docker(self) -> None:
        # No src/Dockerfile means attachment-only content: no image field.
        self.assertEqual(
            self.entry("challenges", "cookie"),
            {
                "id": "cookie",
                "name": "cookie",
                "version": "1.0.0",
                "author": "dev@floatctf.local",
                "category": "web",
                "difficulty": "unknown",
                "tags": [],
                "description": "想成为管理员吗？也许你需要一个特殊的饼干！",
                "flag": {"type": "static"},
                "events": [],
            },
        )

    def test_catalog_event_entry(self) -> None:
        self.assertEqual(
            self.catalog()["events"],
            [
                {
                    "id": "freshcup",
                    "title": "Freshcup Fixture",
                    "description": "Fixture event",
                    "started_at": "2025-01-01 10:00",
                    "ended_at": "2025-01-01 18:00",
                    "challenges": ["comment"],
                    "gameboxes": ["comment"],
                }
            ],
        )

    def test_event_to_challenge_reverse_relation(self) -> None:
        catalog = self.catalog()

        comment_challenge = self.entry("challenges", "comment")
        comment_gamebox = self.entry("gameboxes", "comment")

        self.assertEqual(comment_challenge["events"], ["freshcup"])
        self.assertEqual(comment_gamebox["events"], ["freshcup"])

        # An event only lists what it references.
        self.assertEqual(catalog["events"][0]["challenges"], ["comment"])
        self.assertEqual(catalog["events"][0]["gameboxes"], ["comment"])

    def test_catalog_never_exposes_flag_values(self) -> None:
        catalog = self.catalog()
        rendered = content.render_catalog(catalog)

        for entry in [*catalog["challenges"], *catalog["gameboxes"]]:
            if "flag" in entry:
                self.assertEqual(set(entry["flag"]), {"type"})

        self.assertFalse(FORBIDDEN_CATALOG_KEYS & json_keys(catalog))
        self.assertNotIn("fixture-flag-must-not-leak", rendered)

    def test_container_challenge_has_image_in_catalog(self) -> None:
        catalog = content.build_catalog(SAFE_NAMES_FIXTURE)

        self.assertEqual(
            find_entry(catalog["challenges"], "FloatCTF-qidong")["image"],
            "floatctf/floatctf-qidong:challenge-v1.0.0",
        )
        self.assertEqual(
            find_entry(catalog["challenges"], "题目")["image"],
            "floatctf/challenge-001:challenge-v2.0.0",
        )

    def test_static_challenge_has_no_image_in_catalog(self) -> None:
        catalog = content.build_catalog(SAFE_NAMES_FIXTURE)
        entry = find_entry(catalog["challenges"], "Android_reverse")

        self.assertNotIn("image", entry)
        self.assertIsNone(entry.get("image"))
        self.assertNotIn('"image": null', content.render_catalog(catalog))
        self.assertEqual(entry["id"], "Android_reverse")

    def test_catalog_image_matches_dockerfile_and_pattern(self) -> None:
        catalog = content.build_catalog(SAFE_NAMES_FIXTURE)
        image_pattern = re.compile(
            r"^floatctf/[a-z0-9]+(?:[._-][a-z0-9]+)*"
            r":(?:challenge|gamebox)-v\d+\.\d+\.\d+$"
        )

        for kind, entries in (
            ("challenges", catalog["challenges"]),
            ("gameboxes", catalog["gameboxes"]),
        ):
            for entry in entries:
                dockerfile = (
                    SAFE_NAMES_FIXTURE
                    / kind
                    / entry["id"]
                    / "src"
                    / "Dockerfile"
                )

                if "image" in entry:
                    self.assertTrue(dockerfile.is_file(), entry["id"])
                    self.assertRegex(entry["image"], image_pattern)
                else:
                    self.assertFalse(dockerfile.is_file(), entry["id"])

    def test_catalog_keeps_raw_id_and_unicode_description(self) -> None:
        catalog = content.build_catalog(SAFE_NAMES_FIXTURE)
        rendered = content.render_catalog(catalog)

        self.assertEqual(
            [item["id"] for item in catalog["challenges"]],
            sorted(item["id"] for item in catalog["challenges"]),
        )
        self.assertIn("题目", rendered)
        self.assertIn("Unicode id needs an explicit safe_name", rendered)

    def test_catalog_is_deterministic(self) -> None:
        first = content.render_catalog(content.build_catalog(VALID_FIXTURE))
        second = content.render_catalog(content.build_catalog(VALID_FIXTURE))

        self.assertEqual(first, second)
        self.assertTrue(first.endswith("\n"))
        self.assertNotIn("generated_at", first)

        catalog = self.catalog()
        self.assertEqual(
            [item["id"] for item in catalog["challenges"]],
            sorted(item["id"] for item in catalog["challenges"]),
        )
        self.assertEqual(
            [item["id"] for item in catalog["gameboxes"]],
            sorted(item["id"] for item in catalog["gameboxes"]),
        )
        self.assertEqual(
            [item["id"] for item in catalog["events"]],
            sorted(item["id"] for item in catalog["events"]),
        )

    def test_catalog_check_detects_missing_and_stale_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = copy_fixture(VALID_FIXTURE, Path(tmp) / "content")

            self.assertEqual(quiet(content.main, ["catalog", "--check", "--root", str(root)]), 1)

            self.assertEqual(quiet(content.main, ["catalog", "--root", str(root)]), 0)
            self.assertEqual(quiet(content.main, ["catalog", "--check", "--root", str(root)]), 0)

            (root / "catalog.json").write_text("{}\n", encoding="utf-8")
            self.assertEqual(quiet(content.main, ["catalog", "--check", "--root", str(root)]), 1)

    def test_catalog_round_trips_through_json(self) -> None:
        rendered = content.render_catalog(content.build_catalog(VALID_FIXTURE))

        self.assertEqual(
            json.loads(rendered),
            content.build_catalog(VALID_FIXTURE),
        )
        self.assertIn("注释里面有什么？", rendered)

    def test_catalog_output_writes_to_another_path(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = copy_fixture(VALID_FIXTURE, Path(tmp) / "content")
            target = Path(tmp) / "out" / "catalog.json"

            result = quiet(
                content.main,
                ["catalog", "--output", str(target), "--root", str(root)],
            )

            self.assertEqual(result, 0)
            self.assertTrue(target.is_file())
            self.assertFalse((root / "catalog.json").exists())
            self.assertEqual(
                target.read_text(encoding="utf-8"),
                content.render_catalog(content.build_catalog(root)),
            )

    def test_catalog_check_and_output_are_mutually_exclusive(self) -> None:
        with self.assertRaises(SystemExit) as raised:
            quiet(
                content.main,
                [
                    "catalog",
                    "--check",
                    "--output",
                    "/tmp/never-written.json",
                    "--root",
                    str(VALID_FIXTURE),
                ],
            )

        self.assertEqual(raised.exception.code, 2)

