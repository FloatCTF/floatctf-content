    def test_all_difficulties_are_accepted(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = copy_fixture(VALID_FIXTURE, Path(tmp) / "content")
            meta_path = root / "challenges" / "comment" / "meta.toml"
            original = meta_path.read_text(encoding="utf-8")

            for difficulty in content.DIFFICULTIES:
                meta_path.write_text(
                    original.replace(
                        'difficulty = "easy"', f'difficulty = "{difficulty}"'
                    ),
                    encoding="utf-8",
                )
                self.assertTrue(
                    content.validate(root).ok,
                    f"difficulty '{difficulty}' should be accepted",
                )

    def test_empty_accounts_for_missing_directories(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            result = content.validate(Path(tmp))

            self.assertTrue(result.ok, result.errors)
            self.assertEqual(
                (len(result.challenges), len(result.gameboxes), len(result.events)),
                (0, 0, 0),
            )

    def test_invalid_explicit_safe_name(self) -> None:
        errors = self.errors(INVALID_FIXTURE)

        self.assertIn(
            "challenges/broken_safe_name/meta.toml: invalid safe_name 'Foo Bar'",
            errors,
        )

    def test_underivable_safe_name_requires_explicit_value(self) -> None:
        errors = self.errors(INVALID_FIXTURE)

        self.assertIn(
            "challenges/题目/meta.toml: unable to derive Docker safe_name; "
            "set safe_name explicitly",
            errors,
        )

    def test_explicit_safe_name_makes_unicode_id_valid(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = copy_fixture(SAFE_NAMES_FIXTURE, Path(tmp) / "content")

            self.assertTrue(content.validate(root).ok, content.validate(root).errors)

            meta_path = root / "challenges" / "题目" / "meta.toml"
            meta_path.write_text(
                meta_path.read_text(encoding="utf-8").replace(
                    'safe_name = "challenge-001"\n', ""
                ),
                encoding="utf-8",
            )

            self.assertIn(
                "challenges/题目/meta.toml: unable to derive Docker safe_name; "
                "set safe_name explicitly",
                content.validate(root).errors,
            )

    def test_duplicate_safe_name_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "content"
            write_content(root, "challenges", "Foo")
            write_content(root, "challenges", "foo")

            self.assertIn(
                "duplicate challenge safe_name 'foo': 'Foo' and 'foo'",
                content.validate(root).errors,
            )

    def test_duplicate_safe_name_across_types_is_allowed(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "content"
            write_content(root, "challenges", "foo")
            write_content(root, "gameboxes", "foo")

            result = content.validate(root)

            self.assertTrue(result.ok, result.errors)

    def test_duplicate_event_references(self) -> None:
        errors = self.errors(INVALID_FIXTURE)

        self.assertIn("events/dup.toml: duplicate challenge 'broken_version'", errors)
        self.assertIn("events/dup.toml: duplicate gamebox 'box'", errors)


